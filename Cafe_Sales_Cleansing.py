import pandas as pd
import numpy as np
## Import data ##
from google.colab import files
uploaded = files.upload()

## Load Data ##
df = pd.read_csv('dirty_cafe_sales.csv')
print(df.head())
print(df.info())

## Data Inspection (Checking Missing Values & Duplicate) ##
print("\nMissing Values:")
print(df.isnull().sum())

print("\nDuplicate Rows:")
print(df.duplicated().sum())

## Data Cleaning ##
df.replace(['ERROR','UNKNOWN','N/A'],np.nan,inplace=True)
df['Quantity']=pd.to_numeric(df['Quantity'],errors='coerce')
df['Total Spent']=pd.to_numeric(df['Total Spent'],errors='coerce')
df['Price Per Unit']=pd.to_numeric(df['Price Per Unit'],errors='coerce')
print(df.info())

## Menangani Missing Value ##
df['Payment Method'].fillna('Unknown',inplace=True)
df['Location'].fillna('Unknown',inplace=True)
most_frequent_item = df['Item'].mode()[0]
df['Item'].fillna(most_frequent_item,inplace=True)
print("\nSisa Missing Values setelah dibersihkan:")
print(df[['Item','Payment Method','Location']].isnull().sum())

#Konversi kolom numerik & tangani error teks rusak menjadi NaN
df['Quantity'] = pd.to_numeric(df['Quantity'], errors='coerce')
df['Price Per Unit'] = pd.to_numeric(df['Price Per Unit'], errors='coerce')
df['Total Spent'] = pd.to_numeric(df['Total Spent'], errors='coerce')

# Isi missing value numerik dengan median
df['Quantity'].fillna(df['Quantity'].median(), inplace=True)
df['Price Per Unit'].fillna(df['Price Per Unit'].median(), inplace=True)

## Konversi Tanggal & Bersihkan Baris yang Tanggalnya Kosong
df['Transaction Date'] = pd.to_datetime(df['Transaction Date'], errors='coerce')
# Hapus baris yang tanggalnya NaT (kosong/rusak total)
df.dropna(subset=['Transaction Date'], inplace=True)

## Formating and Text ##
df['Item']=df['Item'].str.strip().str.title()
df['Payment Method']=df['Payment Method'].str.strip().str.title()
df['Location']=df['Location'].str.strip().str.title()
print(df[['Transaction Date','Item','Payment Method','Location']].head())

## counting Total Baris yang duplicate ##
total_duplicate = df.duplicated().sum()
print(f"\nTotal Baris yang Duplicate: {total_duplicate}")
row_duplicate = df[df.duplicated(keep=False)]
print(f"\nBaris yang Duplicate:")
print(row_duplicate)

## Validating & calculate total spent ##
calculated_total = df['Quantity']*df['Price Per Unit']
df['Total Spent'] = df['Total Spent'].fillna(calculated_total)
print("---LAPORAN AKHIR SETELAH CLEANSING---")
print(df.info())
print("\nContoh 5 Data Teratas yang Sudah Bersih")
print(df.head())

file_output = 'cafe_sales_cleaned.csv'
df.to_csv(file_output, index=False)

print(f"\nSukses! Data yang sudah bersih berhasil disimpan ke file: '{file_output}'")

# Cek jumlah total missing values di setiap kolom saat ini
print("Jumlah Missing Values per Kolom:")
print(df.isnull().sum())

